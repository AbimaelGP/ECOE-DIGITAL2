-- ---------------------------------------------------------------------
-- 1. Columnas nuevas en tablas existentes
-- ---------------------------------------------------------------------

-- Circuito al que queda ligado cada médico evaluador (área = modulo_asignado)
alter table public.perfiles_medicos
    add column if not exists circuito_asignado text;

-- Estudios que el estudiante solicitó en la estación (evidencia para el médico)
alter table public.historial_chat_estudiante
    add column if not exists estudios_solicitados jsonb default '[]'::jsonb;

-- ---------------------------------------------------------------------
-- 2. Evaluación del médico evaluador (formulario docente)
--    criterios: [{clave, categoria, dominio, texto, puntaje, nivel, comentario}]
--    estatus:   'borrador' | 'enviada'
-- ---------------------------------------------------------------------
create table if not exists public.evaluacion_docente (
    id                     bigint generated by default as identity primary key,
    matricula              text not null,
    clave_caso             text not null,
    modulo                 text,
    circuito               text,
    area                   text,
    modalidad              text,
    evaluador              text not null,
    criterios              jsonb default '[]'::jsonb,
    comentarios_generales  text,
    calificacion           numeric,
    estatus                text default 'borrador',
    fecha_creacion         timestamptz default now(),
    fecha_envio            timestamptz,
    updated_at             timestamptz default now(),
    unique (matricula, clave_caso, evaluador)
);
create index if not exists idx_evdoc_caso on public.evaluacion_docente(clave_caso);

-- ---------------------------------------------------------------------
-- 3. Evaluación estructurada del chatbot evaluador
--    competencias: [{clave, categoria, dominio, texto, puntaje, nivel,
--                    criterio, evidencias:[{id, mensaje, cita}], para_subir}]
--    transcripcion: copia numerada de la evidencia usada (para auditar)
-- ---------------------------------------------------------------------
create table if not exists public.evaluacion_chatbot (
    id                bigint generated by default as identity primary key,
    matricula         text not null,
    clave_caso        text not null,
    modulo            text,
    modalidad         text,
    competencias      jsonb default '[]'::jsonb,
    calificacion      numeric,
    nivel_global      text,
    resumen           text,
    transcripcion     jsonb default '[]'::jsonb,
    modelo            text,
    prompt_version    text not null default 'v1',
    fecha_evaluacion  timestamptz default now(),
    unique (matricula, clave_caso, prompt_version)
);
create index if not exists idx_evbot_caso on public.evaluacion_chatbot(matricula, clave_caso);

-- ---------------------------------------------------------------------
-- 4. Ponderación chatbot / médico definida por el administrador
--    alcance: 'examen' (valor = 'todos' o una fecha), 'circuito', 'modalidad'
-- ---------------------------------------------------------------------
create table if not exists public.configuracion_ponderacion (
    id                        bigint generated by default as identity primary key,
    alcance                   text not null default 'examen',
    valor                     text not null default 'todos',
    w_chatbot                 numeric not null default 0.5,
    w_medico                  numeric not null default 0.5,
    usar_disponible           boolean default true,
    estandarizado_solo_medico boolean default true,
    bloqueada                 boolean default false,
    actualizado_por           text,
    updated_at                timestamptz default now(),
    unique (alcance, valor)
);
insert into public.configuracion_ponderacion (alcance, valor, w_chatbot, w_medico, actualizado_por)
values ('examen', 'todos', 0.5, 0.5, 'sistema')
on conflict (alcance, valor) do nothing;

-- ---------------------------------------------------------------------
-- 5. Calificación final publicada (una por estudiante y caso)
-- ---------------------------------------------------------------------
create table if not exists public.calificacion_final (
    id                 bigint generated by default as identity primary key,
    matricula          text not null,
    clave_caso         text not null,
    circuito           text,
    modalidad          text,
    nota_chatbot       numeric,
    nota_medico        numeric,
    w_chatbot          numeric,
    w_medico           numeric,
    calificacion       numeric,
    publicada          boolean default false,
    publicada_por      text,
    fecha_publicacion  timestamptz,
    updated_at         timestamptz default now(),
    unique (matricula, clave_caso)
);

-- ---------------------------------------------------------------------
-- 6. Reportes de desacuerdo / criterio incorrecto del chatbot
-- ---------------------------------------------------------------------
create table if not exists public.reportes_chatbot (
    id              bigint generated by default as identity primary key,
    matricula       text,
    clave_caso      text,
    competencia     text,
    tipo            text default 'desacuerdo',  -- desacuerdo | criterio_incorrecto | revision
    comentario      text,
    reportado_por   text,
    rol             text,
    prompt_version  text,
    atendido        boolean default false,
    fecha           timestamptz default now()
);

-- ---------------------------------------------------------------------
-- 7. Seguridad: las tablas nuevas siguen la misma regla que tus tablas
--    actuales. Si "usuarios" tiene RLS activado, se activa también aquí;
--    si no, se dejan igual que las demás para que la app siga funcionando.
-- ---------------------------------------------------------------------
do $$
declare
    rls_actual boolean;
    t text;
begin
    select c.relrowsecurity into rls_actual
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and c.relname = 'usuarios';

    if coalesce(rls_actual, false) then
        foreach t in array array['evaluacion_docente','evaluacion_chatbot',
                                 'configuracion_ponderacion','calificacion_final',
                                 'reportes_chatbot']
        loop
            execute format('alter table public.%I enable row level security', t);
        end loop;
    end if;
end $$;
