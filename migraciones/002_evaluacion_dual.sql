-- =====================================================================
-- ECOE Digital · Migración 002 · Evaluación dual (chatbot + médico)
--
-- SOLO AGREGA: columnas nuevas y tablas nuevas. No borra, no renombra
-- y no modifica ningún dato existente. Se puede ejecutar varias veces.
--
-- Se aplica sola al iniciar la app si existe el secreto DATABASE_URL.
-- Si no, pégala una vez en Supabase → SQL Editor → Run.
